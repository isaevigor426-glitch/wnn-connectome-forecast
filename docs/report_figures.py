"""Generate report-only technical figures from recorded observations.

Run from repository root: python docs/report_figures.py
Data: docs/results/{experiments_3k,submissions}.csv.\nThe local panel uses runs printed by notebook 07, with a derived 3-seed reference mean.
Filenames intentionally do not overlap with the README figures generated by figures.py.
"""
from pathlib import Path
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from matplotlib.patches import FancyBboxPatch, FancyArrowPatch

D = Path(__file__).resolve().parent
OUT = D / 'img'
OUT.mkdir(exist_ok=True)
INK = '#171c26'; GREY='#6b7280'; BG='#ffffff'; RULE='#e7ebf0'
BLUE='#2b70be'; GREEN='#159477'; ORANGE='#e68a36'; LIGHT='#f6f9fc'
plt.rcParams.update({
    'font.family': ['DejaVu Sans'], 'font.size': 10,
    'axes.spines.top': False, 'axes.spines.right': False,
    'axes.spines.left': False, 'axes.edgecolor': RULE,
    'axes.labelcolor': GREY, 'xtick.color': GREY, 'ytick.color': INK,
    'figure.facecolor': BG, 'axes.facecolor': BG,
    'savefig.facecolor': BG, 'savefig.pad_inches': 0.22,
})

def out(fig, name):
    fig.savefig(OUT / name, dpi=200, bbox_inches='tight')
    plt.close(fig)


def local_validation():
    """Only logged GRU ablations from notebook 07 (no untraced LSTM/active numbers)."""
    raw = pd.read_csv(D/'results/experiments_3k.csv')
    specs = [
        ('baseline, seed 0', 'GRU baseline, seed 0'),
        ('baseline, seed 1', 'GRU baseline, seed 1'),
        ('baseline, seed 2', 'GRU baseline, seed 2'),
        ('Pearson + weighted MSE loss', 'GRU + Pearson loss'),
        ('family re-weighting to valid mix', 'GRU + family reweighting'),
        ('GRU 2x256', 'Wider GRU (2 × 256)'),
        ('event features', 'GRU + event features'),
        ('dropout 0.2, weight decay 1e-4', 'GRU + dropout / weight decay'),
        ('input minus rolling mean (500)', 'GRU + rolling-mean features'),
    ]
    rec = []
    for key, label in specs:
        match = raw.loc[raw.experiment.eq(key)]
        assert len(match) == 1, key
        rec.append((label, float(match.iloc[0].is_scored), float(match.iloc[0].all_rows)))
    rows = list(reversed(rec))
    y = np.arange(len(rows))
    fig, axes = plt.subplots(1, 2, figsize=(14.4, 7.0), sharey=True,
                             gridspec_kw={'width_ratios':[1.25, 1], 'wspace':0.045})
    for ax, index, lo, hi, title in [
        (axes[0], 1, .6638, .6698, 'Scored rows · first 300 valid sequences'),
        (axes[1], 2, .4898, .4952, 'All rows · 1,873 valid sequences')]:
        ax.grid(axis='x', color=RULE, lw=.8)
        ax.set_axisbelow(True)
        for i, row in enumerate(rows):
            val=float(row[index]); base='baseline' in row[0]
            color=GREY if base else BLUE
            ax.plot([lo,val],[i,i],color=RULE,lw=2.1,zorder=2)
            ax.scatter(val,i,s=70,color=color,edgecolor='white',linewidth=1.5,zorder=4)
            ax.text(val+.00012,i,f'{val:.4f}', fontsize=9, va='center',color=INK)
        ax.set_xlim(lo,hi)
        ax.set_ylim(-.65,len(rows)-.1)
        ax.set_xlabel('Weighted Pearson (higher is better)',fontsize=10)
        ax.set_title(title,fontsize=11.5,weight='bold',color=INK,loc='left',pad=14)
        ax.tick_params(axis='y',length=0,labelsize=9.6)
    axes[0].set_yticks(y,[r[0] for r in rows]); axes[1].tick_params(axis='y',labelleft=False)
    # Actual min/max of the three baseline seeds, not confidence intervals.
    base_sc=[r[1] for r in rec[:3]]; base_all=[r[2] for r in rec[:3]]
    axes[0].axvspan(min(base_sc),max(base_sc),facecolor=GREY,alpha=.11,zorder=0)
    axes[1].axvspan(min(base_all),max(base_all),facecolor=GREY,alpha=.11,zorder=0)
    fig.suptitle('Local GRU ablations · preserved notebook results',x=.09,y=1.006,
                 horizontalalignment='left',fontsize=17,weight='bold',color=INK)
    fig.text(.09,.945,'Train: 3,000 sequences · three epochs. Scored and all-row metrics use different validation subsets.',
             color=GREY,fontsize=10)
    fig.text(.09,-.006,'Shaded bands: range of 3 baseline seeds, not statistical confidence intervals. Source: notebook 07, run2 output / experiments_3k.csv.',
             fontsize=9.2,color=GREY)
    fig.subplots_adjust(left=.32,right=.984,bottom=.14,top=.84)
    out(fig,'report_local_validation.png')


def public_selection():
    """Exact public submissions, not a controlled activity-selection ablation."""
    sub=pd.read_csv(D/'results/submissions.csv')
    choices=[
        ('ens3final_submission.zip', 'Earlier 3-model blend'),
        ('ens5act_submission.zip', 'Blend with activity-trained GRU'),
        ('final5_act3_submission.zip', 'Five-GRU blend'),
        ('final5_2lstm_submission.zip', '3 GRU + 2 LSTM (earlier blend)'),
        ('final5_3lstm16_submission.zip', '2 GRU + 3 LSTM'),
        ('final5_mx16_submission.zip', '3 GRU + 2 LSTM (best public WP)'),
    ]
    rows=[]
    for filename,label in choices:
        m=sub[sub.file.eq(filename)]
        assert len(m)==1 and pd.notna(m.iloc[0]['public']),filename
        rows.append((label,float(m.iloc[0]['public'])))
    rows=rows[::-1]
    fig,ax=plt.subplots(figsize=(11.9,5.35))
    y=np.arange(len(rows)); lo,hi=.65575,.65760
    ax.grid(axis='x',color=RULE,lw=.9);ax.set_axisbelow(True)
    for i,(label,val) in enumerate(rows):
        color=GREEN if 'best public' in label else BLUE
        ax.plot([lo,val],[i,i],lw=2.1,color=RULE,zorder=2)
        ax.scatter(val,i,s=85,color=color,edgecolor='white',linewidth=1.4,zorder=3)
        ax.text(val+.000035,i,f'{val:.5f}',va='center',fontsize=10,color=INK)
    ax.set_yticks(y,[r[0] for r in rows]);ax.tick_params(axis='y',length=0,labelsize=10)
    ax.set_xlim(lo,hi);ax.set_ylim(-.65,len(rows)-.15)
    ax.set_xlabel('Public Weighted Pearson (higher is better)')
    fig.suptitle('Public submissions · activity-trained GRU and ensemble variants', x=.046,y=.983,
                 ha='left',color=INK,weight='bold',fontsize=16)
    fig.text(.046,.906,'Different architectures, checkpoints and training data. These are NOT single-variable ablations.',
             color=GREY,fontsize=10)
    fig.text(.046,.033,'Source: docs/results/submissions.csv · observed public scores; private-test quality not yet known.',
             color=GREY,fontsize=9.3)
    fig.subplots_adjust(left=.38,right=.975,top=.79,bottom=.18)
    out(fig,'report_public_selection.png')


