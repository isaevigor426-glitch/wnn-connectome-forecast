def runtime_budget():
    submissions = pd.read_csv(D/'results/submissions.csv')
    find=lambda n: float(submissions.loc[submissions.file.eq(n),'duration_min'].iloc[0])
    a,b=find('final5_mx16_submission.zip'),find('final5_2lstm_submission.zip')
    fig,ax=plt.subplots(figsize=(11.5,4.65))
    labels=['Best 5-model blend · 3 GRU + 2 LSTM','Earlier 5-model blend · 3 GRU + 2 LSTM']
    vals=[a,b]
    yy=np.array([1,0]); colors=[GREEN,BLUE]
    ax.barh(yy,vals,height=.38,color=colors,zorder=3)
    for i,v in enumerate(vals):
        ax.text(v+.7,yy[i],f'{v:.1f} min',va='center',fontsize=11,color=INK,weight='bold')
    ax.axvline(60,color=ORANGE,ls='--',lw=1.8,zorder=3)
    ax.text(60.2,1.53,'60-minute limit',color=ORANGE,fontsize=9.5,ha='right')
    ax.set_yticks(yy,labels); ax.set_xlim(0,65.5);ax.set_ylim(-.65,1.75)
    ax.set_xlabel('Observed end-to-end test runtime (minutes)',color=GREY)
    ax.grid(axis='x',color=RULE,lw=1);ax.set_axisbelow(True)
    ax.tick_params(axis='y',length=0,labelsize=9.4)
    ax.spines['bottom'].set_color(RULE)
    fig.suptitle('Single-core inference: speed is part of model quality',x=.055,y=.985,ha='left',fontsize=16,color=INK,weight='bold')
    fig.text(.055,.89,'39.4M rows × 1 CPU core → 60 minutes = 91.4 μs/row average budget. Best observed: ~66.3 μs/row.',color=GREY,fontsize=10)
    fig.text(.055,.055,'These submissions used different LSTM checkpoints and weight formats; the runtime difference is NOT a controlled FP16-only effect.',color=GREY,fontsize=9.2)
    fig.subplots_adjust(left=.36,right=.975,top=.75,bottom=.19)
    out(fig,'report_runtime_budget.png')

